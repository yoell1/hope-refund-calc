-- 93_v2.8에서_v2.9로.sql · 이미 v2.8로 만든 계정(교육원 공용 DB 포함)을 v2.9로 올리는 스크립트 (10/23)
-- 새로 만드는 계정은 이 파일 없이 01 → 02 → 03 만 실행하면 v2.9가 됨
--
-- v2.9에서 바뀐 것
--   1) 데이터 구분 DATA_ORIGIN : COLLECTED(수집) / GENERATED(생성·더미) / INPUT(사이트 입력)
--      MEMBER · INCOME · CARD_UPLOAD (기본값 INPUT) · MERCHANT_LIST (기본값 COLLECTED)
--      카드 내역 EXPENSE는 CARD_UPLOAD의 구분을 따름 (칸 없음)
--   2) 세법 기준값 근거 SOURCE_NOTE : DEDUCTION_TYPE · TAX_BRACKET · BENEFIT_CONDITION
--   3) MERCHANT_LIST.UPDATED_AT (수정일)
-- 새 칸은 모두 테이블 맨 뒤에 붙음 (01_schema.sql 칸 순서와 같음)

SET DEFINE OFF

-- ─────────────────────────────────────────────
-- 1) 데이터 구분 칸 추가
--    기존 행은 기본값(INPUT)으로 채워진 뒤, 아래 UPDATE로 더미 범위만 GENERATED로 바꿈
--    더미 범위: 회원·소득 MEMBER_ID 1~1001 (test0001~test1000 + admin) · 업로드 UPLOAD_ID 1~100
-- ─────────────────────────────────────────────
ALTER TABLE MEMBER      ADD (DATA_ORIGIN VARCHAR2(10) DEFAULT 'INPUT' NOT NULL);
ALTER TABLE INCOME      ADD (DATA_ORIGIN VARCHAR2(10) DEFAULT 'INPUT' NOT NULL);
ALTER TABLE CARD_UPLOAD ADD (DATA_ORIGIN VARCHAR2(10) DEFAULT 'INPUT' NOT NULL);
ALTER TABLE MERCHANT_LIST ADD (DATA_ORIGIN VARCHAR2(10) DEFAULT 'COLLECTED' NOT NULL,
                               UPDATED_AT  DATE         DEFAULT SYSDATE NOT NULL);

ALTER TABLE MEMBER        ADD CONSTRAINT CK_MEMBER_ORIGIN        CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT'));
ALTER TABLE INCOME        ADD CONSTRAINT CK_INCOME_ORIGIN        CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT'));
ALTER TABLE CARD_UPLOAD   ADD CONSTRAINT CK_CARD_UPLOAD_ORIGIN   CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT'));
ALTER TABLE MERCHANT_LIST ADD CONSTRAINT CK_MERCHANT_LIST_ORIGIN CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT'));

UPDATE MEMBER      SET DATA_ORIGIN = 'GENERATED' WHERE MEMBER_ID BETWEEN 1 AND 1001;
UPDATE INCOME      SET DATA_ORIGIN = 'GENERATED' WHERE MEMBER_ID BETWEEN 1 AND 1001;
UPDATE CARD_UPLOAD SET DATA_ORIGIN = 'GENERATED' WHERE UPLOAD_ID BETWEEN 1 AND 100;

-- 가맹점 목록 수정일: 적재일(10/20)로 맞추고, 10/22에 고친 9행(94_가맹점목록_정제수정.sql)은 10/22로
UPDATE MERCHANT_LIST SET UPDATED_AT = DATE '2026-10-20';
UPDATE MERCHANT_LIST SET UPDATED_AT = DATE '2026-10-22'
 WHERE LIST_ID IN (1692, 7060, 18770, 31641, 43431, 49312, 53293, 55148, 60029);

-- ─────────────────────────────────────────────
-- 2) 세법 기준값 근거 칸 추가 + 2026년 행 채우기 (02_기준데이터.sql 주석과 같은 내용)
-- ─────────────────────────────────────────────
ALTER TABLE DEDUCTION_TYPE    ADD (SOURCE_NOTE VARCHAR2(200));
ALTER TABLE TAX_BRACKET       ADD (SOURCE_NOTE VARCHAR2(200));
ALTER TABLE BENEFIT_CONDITION ADD (SOURCE_NOTE VARCHAR2(200));

UPDATE DEDUCTION_TYPE SET SOURCE_NOTE = '국세청 신고안내 132p · 조특법 §126의2'
 WHERE TAX_YEAR = 2026 AND TYPE_CODE LIKE 'CARD\_%' ESCAPE '\';
UPDATE DEDUCTION_TYPE SET SOURCE_NOTE = '국세청 신고안내 95p'                  WHERE TAX_YEAR = 2026 AND TYPE_CODE = 'PERSON_BASIC';
UPDATE DEDUCTION_TYPE SET SOURCE_NOTE = '국세청 신고안내 120p · 조특법 §87'     WHERE TAX_YEAR = 2026 AND TYPE_CODE = 'HOUSING_SAVING';
UPDATE DEDUCTION_TYPE SET SOURCE_NOTE = '국세청 신고안내 요약표'                WHERE TAX_YEAR = 2026 AND TYPE_CODE IN ('PENSION_HIGH', 'PENSION');
UPDATE DEDUCTION_TYPE SET SOURCE_NOTE = '국세청 신고안내 202p'                  WHERE TAX_YEAR = 2026 AND TYPE_CODE IN ('RENT_HIGH', 'RENT');
UPDATE DEDUCTION_TYPE SET SOURCE_NOTE = '국세청 신고안내 148·150p · 조특법 §30' WHERE TAX_YEAR = 2026 AND TYPE_CODE = 'SME_YOUTH';

UPDATE TAX_BRACKET SET SOURCE_NOTE = '국세청 신고안내 요약표 (기본세율)' WHERE TAX_YEAR = 2026 AND BRACKET_TYPE = 'TAX_RATE';
UPDATE TAX_BRACKET SET SOURCE_NOTE = '국세청 신고안내 94p'               WHERE TAX_YEAR = 2026 AND BRACKET_TYPE = 'EARNED_DEDUCTION';
UPDATE TAX_BRACKET SET SOURCE_NOTE = '국세청 신고안내 162p'              WHERE TAX_YEAR = 2026 AND BRACKET_TYPE = 'EARNED_CREDIT';

UPDATE BENEFIT_CONDITION SET SOURCE_NOTE = '국세청 신고안내 148·150p · 조특법 §30' WHERE TAX_YEAR = 2026 AND BENEFIT_CODE = 'SME_YOUTH';
UPDATE BENEFIT_CONDITION SET SOURCE_NOTE = '국세청 신고안내 202p'                  WHERE TAX_YEAR = 2026 AND BENEFIT_CODE = 'RENT';
UPDATE BENEFIT_CONDITION SET SOURCE_NOTE = '국세청 신고안내 120p · 조특법 §87'     WHERE TAX_YEAR = 2026 AND BENEFIT_CODE = 'HOUSING_SAVING';

COMMIT;

-- ─────────────────────────────────────────────
-- 3) 칸 설명
-- ─────────────────────────────────────────────
COMMENT ON COLUMN MEMBER.DATA_ORIGIN IS '데이터 구분 COLLECTED(수집)/GENERATED(생성·더미)/INPUT(사이트 입력)';
COMMENT ON COLUMN INCOME.DATA_ORIGIN IS '데이터 구분 COLLECTED(수집)/GENERATED(생성·더미)/INPUT(사이트 입력)';
COMMENT ON COLUMN CARD_UPLOAD.DATA_ORIGIN IS '데이터 구분 COLLECTED(수집)/GENERATED(생성·더미)/INPUT(사이트 입력)';
COMMENT ON COLUMN MERCHANT_LIST.DATA_ORIGIN IS '데이터 구분 COLLECTED(수집)/GENERATED(생성·더미)/INPUT(사이트 입력)';
COMMENT ON COLUMN MERCHANT_LIST.UPDATED_AT IS '수정일';
COMMENT ON COLUMN DEDUCTION_TYPE.SOURCE_NOTE IS '근거(국세청 신고안내 쪽수·법 조문)';
COMMENT ON COLUMN TAX_BRACKET.SOURCE_NOTE IS '근거(국세청 신고안내 쪽수·법 조문)';
COMMENT ON COLUMN BENEFIT_CONDITION.SOURCE_NOTE IS '근거(국세청 신고안내 쪽수·법 조문)';

-- ─────────────────────────────────────────────
-- 4) 확인 (예상 결과는 오른쪽 주석)
-- ─────────────────────────────────────────────
SELECT 'MEMBER' T, DATA_ORIGIN, COUNT(*) N FROM MEMBER GROUP BY DATA_ORIGIN           -- GENERATED 1,001 (+ 사이트에서 가입한 회원은 INPUT)
UNION ALL SELECT 'INCOME', DATA_ORIGIN, COUNT(*) FROM INCOME GROUP BY DATA_ORIGIN     -- GENERATED 1,000
UNION ALL SELECT 'CARD_UPLOAD', DATA_ORIGIN, COUNT(*) FROM CARD_UPLOAD GROUP BY DATA_ORIGIN   -- GENERATED 100
UNION ALL SELECT 'MERCHANT_LIST', DATA_ORIGIN, COUNT(*) FROM MERCHANT_LIST GROUP BY DATA_ORIGIN; -- COLLECTED 80,665

SELECT (SELECT COUNT(*) FROM DEDUCTION_TYPE    WHERE TAX_YEAR = 2026 AND SOURCE_NOTE IS NULL) AS 공제_근거없음,  -- 0
       (SELECT COUNT(*) FROM TAX_BRACKET       WHERE TAX_YEAR = 2026 AND SOURCE_NOTE IS NULL) AS 구간_근거없음,  -- 0
       (SELECT COUNT(*) FROM BENEFIT_CONDITION WHERE TAX_YEAR = 2026 AND SOURCE_NOTE IS NULL) AS 혜택_근거없음,  -- 0
       (SELECT COUNT(*) FROM USER_CONSTRAINTS WHERE CONSTRAINT_TYPE = 'C' AND CONSTRAINT_NAME LIKE 'CK\_%' ESCAPE '\') AS CHECK_수, -- 33
       (SELECT COUNT(*) FROM MERCHANT_LIST WHERE UPDATED_AT = DATE '2026-10-22') AS 목록_10월22일_수정  -- 9
  FROM DUAL;
