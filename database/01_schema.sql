-- ▶ GROUP_STAT: 그룹 비교 통계 (v3.8 · D-11 · 「나와 비슷한 사람들은」 · 그룹 1개 = 1행 · 국세통계 2024년 귀속)
--   성별·연령대 그룹과 급여 구간 그룹은 원본 표가 달라 교차(예: 30대 남성 + 4천만대) 행은 없음
CREATE TABLE GROUP_STAT (
  STAT_ID           NUMBER        NOT NULL,         -- 통계번호
  FILE_ID           NUMBER        NOT NULL,         -- 이 값이 나온 정제 파일 → STAT_FILE
  TAX_YEAR          NUMBER(4)     NOT NULL,         -- 귀속 연도
  GROUP_TYPE        VARCHAR2(10)  NOT NULL,         -- GENDER_AGE(성별·연령대)/SALARY(급여 구간)
  GROUP_LABEL       VARCHAR2(50)  NOT NULL,         -- 그룹 이름 (정제 파일 표기 · 화면 표시용)
  GENDER            CHAR(1),                        -- 성별 M/F (성별·연령대 그룹만)
  AGE_MIN           NUMBER(3),                      -- 나이 시작(이상 · NULL = 하한 없음)
  AGE_MAX           NUMBER(3),                      -- 나이 끝(이하 · NULL = 상한 없음)
  SALARY_MIN        NUMBER(15),                     -- 총급여 구간 시작(초과 · 원)
  SALARY_MAX        NUMBER(15),                     -- 총급여 구간 끝(이하 · 원 · NULL = 상한 없음)
  PEOPLE_COUNT      NUMBER(12)    NOT NULL,         -- 인원
  TOTAL_SALARY_MIL  NUMBER(15)    NOT NULL,         -- 총급여 합계(백만 원)
  AVG_SALARY        NUMBER(15)    NOT NULL,         -- 1인당 총급여(원)
  AVG_DECIDED_TAX   NUMBER(15)    NOT NULL,         -- 1인당 결정세액(원)
  AVG_WITHHELD_TAX  NUMBER(15)    NOT NULL,         -- 1인당 기납부세액(원)
  AVG_REFUND_TAX    NUMBER(15)    NOT NULL,         -- 1인당 환급세액(원)
  AVG_PAYABLE_TAX   NUMBER(15)    NOT NULL,         -- 1인당 납부할세액(원)
  AVG_CARD_DEDUCTION NUMBER(15)   NOT NULL,         -- 1인당 신용카드등소득공제(원)
  AVG_RENT_CREDIT   NUMBER(15)    NOT NULL,         -- 1인당 월세세액공제(원)
  AVG_SME_REDUCTION NUMBER(15)    NOT NULL,         -- 1인당 중소기업취업자감면(원)
  CONSTRAINT PK_GROUP_STAT PRIMARY KEY (STAT_ID),
  CONSTRAINT FK_GROUP_STAT_FILE FOREIGN KEY (FILE_ID) REFERENCES STAT_FILE (FILE_ID),
  CONSTRAINT UQ_GROUP_STAT_GROUP UNIQUE (TAX_YEAR, GROUP_TYPE, GROUP_LABEL),
  CONSTRAINT CK_GROUP_STAT_TYPE CHECK (GROUP_TYPE IN ('GENDER_AGE', 'SALARY')),
  CONSTRAINT CK_GROUP_STAT_GENDER CHECK (GENDER IN ('M', 'F')),
  CONSTRAINT CK_GROUP_STAT_GROUP CHECK ((GROUP_TYPE = 'GENDER_AGE' AND GENDER IS NOT NULL AND SALARY_MIN IS NULL AND SALARY_MAX IS NULL)
                                    OR (GROUP_TYPE = 'SALARY' AND GENDER IS NULL AND AGE_MIN IS NULL AND AGE_MAX IS NULL)),  -- 그룹 종류에 맞는 칸만
  CONSTRAINT CK_GROUP_STAT_AMOUNT CHECK (PEOPLE_COUNT >= 0 AND TOTAL_SALARY_MIL >= 0 AND AVG_SALARY >= 0 AND AVG_DECIDED_TAX >= 0 AND AVG_WITHHELD_TAX >= 0
                                     AND AVG_REFUND_TAX >= 0 AND AVG_PAYABLE_TAX >= 0 AND AVG_CARD_DEDUCTION >= 0 AND AVG_RENT_CREDIT >= 0 AND AVG_SME_REDUCTION >= 0)
);

