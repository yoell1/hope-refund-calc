-- ▶ MEMBER: 회원
CREATE TABLE MEMBER (
  MEMBER_ID         NUMBER        NOT NULL,         -- 회원번호
  LOGIN_ID          VARCHAR2(50)  NOT NULL,         -- 아이디
  EMAIL             VARCHAR2(100) NOT NULL,         -- 이메일(아이디 찾기·비밀번호 재설정 인증용, 화면 마스킹)
  PASSWORD          VARCHAR2(255) NOT NULL,         -- 비밀번호(BCrypt)
  NAME              VARCHAR2(50),                   -- 이름 · v3.5부터 수집 안 함(NULL 허용 · 가상데이터만 값 있음 · 화면 호칭 고객님/사용자님)
  BIRTH_DATE        DATE          NOT NULL,         -- 생년월일
  GENDER            CHAR(1),                        -- 성별 M/F
  MILITARY_MONTHS   NUMBER(3)     DEFAULT 0 NOT NULL, -- 군 복무 개월(선택, 최대 72 인정)
  HIRE_DATE         DATE,                           -- 입사일
  COMPANY_SIZE      VARCHAR2(10),                   -- 회사 규모 SME/MID/LARGE
  HOMELESS_HEAD_YN  CHAR(1)       DEFAULT 'N' NOT NULL, -- 무주택 세대주 Y/N
  ROLE              VARCHAR2(10)  DEFAULT 'USER' NOT NULL, -- USER/ADMIN
  STATUS            VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL, -- ACTIVE/WITHDRAWN
  CREATED_AT        DATE          DEFAULT SYSDATE NOT NULL, -- 가입일
  UPDATED_AT        DATE          DEFAULT SYSDATE NOT NULL, -- 회원정보 수정일
  WITHDRAWN_AT      DATE,                           -- 탈퇴일 · v3.8(D-21): 30일 유예기간 동안 아이디·이메일 유지 → 30일 지나면 withdrawn_회원번호로 식별 불가 처리(97번 SQL)
  TERMS_AGREED_AT   DATE          NOT NULL,         -- 이용약관 동의 일시(필수)
  PRIVACY_AGREED_AT DATE          NOT NULL,         -- 개인정보 수집·이용 동의 일시(필수)
  DATA_ORIGIN       VARCHAR2(10)  DEFAULT 'INPUT' NOT NULL, -- v2.9 데이터 구분 COLLECTED(수집)/GENERATED(생성·더미)/INPUT(사이트 입력)
  LOGIN_FAIL_COUNT  NUMBER(2)     DEFAULT 0 NOT NULL, -- v3.0 로그인 연속 실패 횟수 (5번째 실패 시 잠그고 0으로 되돌림 · 잠긴 동안은 안 올림 · 성공하면 0)
  LOCKED_UNTIL      DATE,                           -- v3.0 이 시각까지 로그인 막음 (NULL = 잠금 없음 · 비교는 DB의 SYSDATE로)
  TERMS_VERSION     VARCHAR2(10)  NOT NULL,         -- v3.0 동의한 이용약관 버전 (기본값 없음 → 가입 시 백엔드가 현재 버전을 꼭 넣음)
  PRIVACY_VERSION   VARCHAR2(10)  NOT NULL,         -- v3.0 동의한 개인정보 처리방침 버전 (기본값 없음) · v3.0 칸 4개는 맨 뒤
  EMAIL_VERIFIED_YN CHAR(1)       DEFAULT 'N' NOT NULL, -- v3.4 이메일 인증 여부 (가입 때 인증 메일 코드 확인되면 Y · 비밀번호 재설정은 Y인 회원만 · 남의 이메일로 가입 방지)
  FINANCE_AGREED_AT DATE          NOT NULL,         -- v3.8 금융 정보(소득·카드 내역) 저장 동의 일시 (필수 · D-17 · 가입 때 별도 체크박스)
  FINANCE_VERSION   VARCHAR2(10)  NOT NULL,         -- v3.8 동의한 금융 정보 저장 동의서 버전 (기본값 없음 → 가입 시 백엔드가 꼭 넣음)
  CONSTRAINT PK_MEMBER PRIMARY KEY (MEMBER_ID),
  CONSTRAINT UQ_MEMBER_LOGIN_ID UNIQUE (LOGIN_ID),
  CONSTRAINT UQ_MEMBER_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_MEMBER_EMAIL CHECK (EMAIL LIKE '%_@_%._%'),
  CONSTRAINT CK_MEMBER_EMAIL_LOWER CHECK (EMAIL = LOWER(EMAIL)),  -- v2.7 소문자로만 저장 → 대소문자만 다른 중복 가입 방지 (백엔드에서 LOWER 후 저장·조회)
  CONSTRAINT CK_MEMBER_MILITARY CHECK (MILITARY_MONTHS >= 0),
  CONSTRAINT CK_MEMBER_GENDER CHECK (GENDER IN ('M', 'F')),
  CONSTRAINT CK_MEMBER_COMPANY_SIZE CHECK (COMPANY_SIZE IN ('SME', 'MID', 'LARGE')),
  CONSTRAINT CK_MEMBER_HOMELESS CHECK (HOMELESS_HEAD_YN IN ('Y', 'N')),
  CONSTRAINT CK_MEMBER_ROLE CHECK (ROLE IN ('USER', 'ADMIN')),
  CONSTRAINT CK_MEMBER_STATUS CHECK (STATUS IN ('ACTIVE', 'WITHDRAWN')),
  CONSTRAINT CK_MEMBER_ORIGIN CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT')),
  CONSTRAINT CK_MEMBER_WITHDRAWN CHECK ((STATUS = 'ACTIVE' AND WITHDRAWN_AT IS NULL) OR (STATUS = 'WITHDRAWN' AND WITHDRAWN_AT IS NOT NULL)),
  CONSTRAINT CK_MEMBER_LOGIN_FAIL CHECK (LOGIN_FAIL_COUNT >= 0),  -- v3.0
  CONSTRAINT CK_MEMBER_EMAIL_VERIFIED CHECK (EMAIL_VERIFIED_YN IN ('Y', 'N')),  -- v3.4
  CONSTRAINT CK_MEMBER_GENDER_REQ CHECK (GENDER IS NOT NULL OR ROLE = 'ADMIN' OR STATUS = 'WITHDRAWN')  -- v3.9 회원가입 성별 필수 · 관리자는 빈칸 허용 · 탈퇴 회원 예외 (성별 없는 관리자를 일반 회원으로 내리기는 백엔드에서 차단)
);

-- ▶ INCOME: 연도별 소득·납입 정보
CREATE TABLE INCOME (
  INCOME_ID         NUMBER        NOT NULL,         -- 소득번호
  MEMBER_ID         NUMBER        NOT NULL,         -- 회원번호 → MEMBER
  TAX_YEAR          NUMBER(4)     NOT NULL,         -- 귀속 연도
  TOTAL_SALARY      NUMBER(12)    NOT NULL,         -- 연간 예상 총급여
  WITHHELD_TAX      NUMBER(12)    NOT NULL,         -- 기납부 소득세
  NATIONAL_PENSION  NUMBER(12)    DEFAULT 0 NOT NULL, -- v3.9 국민연금보험료(본인 부담 · 연금보험료공제 소법 §51의3 · 표준세액공제와 같이 받음) · 옛 SOCIAL_INSURANCE
  DEPENDENTS        NUMBER(2)     DEFAULT 0 NOT NULL, -- 부양가족 수
  MONTHLY_RENT      NUMBER(10)    DEFAULT 0 NOT NULL, -- 월 월세액
  HOUSING_SAVING    NUMBER(10)    DEFAULT 0 NOT NULL, -- 주택청약 연 납입액
  PENSION_SAVING    NUMBER(10)    DEFAULT 0 NOT NULL, -- 연금저축·IRP 연 납입액
  SME_REDUCTION_YN  CHAR(1)       DEFAULT 'N' NOT NULL, -- 중소기업 감면 신청 여부
  UPDATED_AT        DATE          DEFAULT SYSDATE NOT NULL, -- 수정일
  CREATED_AT        DATE          DEFAULT SYSDATE NOT NULL, -- 등록일 (v2.8 · ALTER로 추가한 계정과 칸 순서를 맞추려고 맨 뒤에 둠)
  DATA_ORIGIN       VARCHAR2(10)  DEFAULT 'INPUT' NOT NULL, -- v2.9 데이터 구분 COLLECTED/GENERATED/INPUT
  CHILDREN          NUMBER(2)     DEFAULT 0 NOT NULL, -- v3.3 20세 이하 자녀 수(카드 공제 자녀 한도용 · 부양가족 수 이하인지는 백엔드 확인 · ALTER 계정과 칸 순서 맞추려고 맨 뒤)
  HEALTH_INSURANCE  NUMBER(12)    DEFAULT 0 NOT NULL, -- v3.9 건강·고용·노인장기요양보험료(본인 부담 · 특별소득공제 소법 §52① · 표준세액공제 13만원과 둘 중 하나) · ALTER 계정과 칸 순서 맞추려고 맨 뒤
  CONSTRAINT PK_INCOME PRIMARY KEY (INCOME_ID),
  CONSTRAINT UQ_INCOME_MEMBER_YEAR UNIQUE (MEMBER_ID, TAX_YEAR),
  CONSTRAINT FK_INCOME_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (MEMBER_ID),
  CONSTRAINT CK_INCOME_SME_YN CHECK (SME_REDUCTION_YN IN ('Y', 'N')),
  CONSTRAINT CK_INCOME_ORIGIN CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT')),
  CONSTRAINT CK_INCOME_AMOUNT CHECK (TOTAL_SALARY >= 0 AND WITHHELD_TAX >= 0 AND NATIONAL_PENSION >= 0 AND DEPENDENTS >= 0
                                     AND MONTHLY_RENT >= 0 AND HOUSING_SAVING >= 0 AND PENSION_SAVING >= 0 AND CHILDREN >= 0 AND HEALTH_INSURANCE >= 0)  -- v2.7 음수 입력 방지 · v3.3 CHILDREN · v3.9 국민연금·건강보험료
);

-- ▶ CARD_UPLOAD: 카드 내역 업로드(파일만)
CREATE TABLE CARD_UPLOAD (
  UPLOAD_ID         NUMBER        NOT NULL,         -- 업로드번호
  MEMBER_ID         NUMBER        NOT NULL,         -- 회원번호 → MEMBER
  FILE_NAME         VARCHAR2(255) NOT NULL,         -- 원본 파일명
  ROW_COUNT         NUMBER(6)     DEFAULT 0 NOT NULL, -- 읽은 건수
  UPLOADED_AT       DATE          DEFAULT SYSDATE NOT NULL, -- 업로드일
  DATA_ORIGIN       VARCHAR2(10)  DEFAULT 'INPUT' NOT NULL, -- v2.9 데이터 구분 (카드 내역 EXPENSE는 이 업로드의 구분을 따름)
  CONSTRAINT PK_CARD_UPLOAD PRIMARY KEY (UPLOAD_ID),
  CONSTRAINT UQ_CARD_UPLOAD_MEMBER UNIQUE (UPLOAD_ID, MEMBER_ID),  -- v3.0 EXPENSE가 (업로드, 회원) 두 칸으로 가리키려고 둠
  CONSTRAINT FK_CARD_UPLOAD_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (MEMBER_ID),
  CONSTRAINT CK_CARD_UPLOAD_ORIGIN CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT'))
);

-- ▶ SPEND_CATEGORY: 지출 분류 항목(5개)
CREATE TABLE SPEND_CATEGORY (
  CATEGORY_ID       NUMBER        NOT NULL,         -- 분류번호
  CATEGORY_CODE     VARCHAR2(20)  NOT NULL,         -- GENERAL/TRANSIT/MARKET/CULTURE/EXCLUDED
  CATEGORY_NAME     VARCHAR2(50)  NOT NULL,         -- 화면 표시 이름
  USE_YN            CHAR(1)       DEFAULT 'Y' NOT NULL, -- 사용 여부
  CONSTRAINT PK_SPEND_CATEGORY PRIMARY KEY (CATEGORY_ID),
  CONSTRAINT UQ_SPEND_CATEGORY_CODE UNIQUE (CATEGORY_CODE),
  CONSTRAINT CK_SPEND_CATEGORY_USE CHECK (USE_YN IN ('Y', 'N'))
);

-- ▶ MERCHANT_LIST: 분류용 공공 목록(상호명 대조)
CREATE TABLE MERCHANT_LIST (
  LIST_ID           NUMBER        NOT NULL,         -- 목록번호
  MERCHANT_NAME     VARCHAR2(200) NOT NULL,         -- 원본 상호명
  NORMALIZED_NAME   VARCHAR2(200) NOT NULL,         -- 정제한 이름(대조용)
  MATCH_TYPE        VARCHAR2(10)  DEFAULT 'EXACT' NOT NULL, -- EXACT(이름 같으면)/CONTAINS(가맹점명에 포함되면)
  CATEGORY_ID       NUMBER        NOT NULL,         -- 분류 → SPEND_CATEGORY
  EXCLUDE_ITEM      VARCHAR2(100),                  -- 제외 항목(국세청 책자 135쪽, 공제 대상 아님만)
  SOURCE_NAME       VARCHAR2(100) NOT NULL,         -- 출처 데이터셋
  BASE_DATE         DATE,                           -- 데이터 기준일
  USE_YN            CHAR(1)       DEFAULT 'Y' NOT NULL, -- 사용 여부
  DATA_ORIGIN       VARCHAR2(10)  DEFAULT 'COLLECTED' NOT NULL, -- v2.9 데이터 구분 (공공데이터 = COLLECTED, 팀이 직접 추가한 행 = INPUT)
  UPDATED_AT        DATE          DEFAULT SYSDATE NOT NULL, -- v2.9 수정일 (목록을 고치면 SYSDATE로 갱신)
  CONSTRAINT PK_MERCHANT_LIST PRIMARY KEY (LIST_ID),
  CONSTRAINT UQ_MERCHANT_LIST_NAME UNIQUE (NORMALIZED_NAME, CATEGORY_ID),  -- v3.0 같은 분류에 같은 정제 이름 중복 금지 · 이름 대조 조회 인덱스 겸용 (USE_YN='N' 행도 포함 → 다시 쓸 땐 새 행 대신 기존 행을 'Y'로)
  CONSTRAINT FK_MERCHANT_LIST_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES SPEND_CATEGORY (CATEGORY_ID),
  CONSTRAINT CK_MERCHANT_LIST_MATCH CHECK (MATCH_TYPE IN ('EXACT', 'CONTAINS')),
  CONSTRAINT CK_MERCHANT_LIST_USE CHECK (USE_YN IN ('Y', 'N')),
  CONSTRAINT CK_MERCHANT_LIST_ORIGIN CHECK (DATA_ORIGIN IN ('COLLECTED', 'GENERATED', 'INPUT'))
);

-- ▶ EXPENSE: 지출 내역(건별)+분류 결과
CREATE TABLE EXPENSE (
  EXPENSE_ID        NUMBER        NOT NULL,         -- 지출번호
  MEMBER_ID         NUMBER        NOT NULL,         -- 회원번호 → MEMBER
  UPLOAD_ID         NUMBER        NOT NULL,         -- 업로드번호 → CARD_UPLOAD (필수)
  USED_DATE         DATE          NOT NULL,         -- 사용일
  MERCHANT_NAME     VARCHAR2(200) NOT NULL,         -- 가맹점명
  PAY_METHOD        VARCHAR2(10)  NOT NULL,         -- 결제수단 CREDIT(신용)/CHECK(체크)/CASH(현금영수증)
  AMOUNT            NUMBER(12)    NOT NULL,         -- 금액
  CATEGORY_ID       NUMBER        NOT NULL,         -- 분류 결과 → SPEND_CATEGORY
  LIST_ID           NUMBER,                         -- 일치한 목록 행 → MERCHANT_LIST (일반이면 NULL)
  CONSTRAINT PK_EXPENSE PRIMARY KEY (EXPENSE_ID),
  CONSTRAINT FK_EXPENSE_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (MEMBER_ID),
  CONSTRAINT FK_EXPENSE_UPLOAD FOREIGN KEY (UPLOAD_ID, MEMBER_ID) REFERENCES CARD_UPLOAD (UPLOAD_ID, MEMBER_ID) ON DELETE CASCADE,  -- v3.0 지출 회원 = 업로드 회원 · 업로드 삭제 시 지출도 삭제
  CONSTRAINT FK_EXPENSE_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES SPEND_CATEGORY (CATEGORY_ID),
  CONSTRAINT FK_EXPENSE_LIST FOREIGN KEY (LIST_ID) REFERENCES MERCHANT_LIST (LIST_ID),
  CONSTRAINT CK_EXPENSE_PAY CHECK (PAY_METHOD IN ('CREDIT', 'CHECK', 'CASH'))
);

-- ▶ DEDUCTION_TYPE: 공제 항목 기준값
CREATE TABLE DEDUCTION_TYPE (
  TYPE_ID           NUMBER        NOT NULL,         -- 항목번호
  TAX_YEAR          NUMBER(4)     NOT NULL,         -- 적용 연도
  TYPE_CODE         VARCHAR2(30)  NOT NULL,         -- 계산 코드 (v3.6 같은 코드가 총급여 구간별로 여러 행)
  TYPE_NAME         VARCHAR2(50)  NOT NULL,         -- 항목명
  DEDUCTION_KIND    VARCHAR2(20)  NOT NULL,         -- CARD/CARD_RULE/INCOME_DEDUCTION/TAX_CREDIT/TAX_REDUCTION
  RATE              NUMBER(5,2)   NOT NULL,         -- 공제율·감면율(%)
  LIMIT_AMOUNT      NUMBER(12),                     -- 연 한도
