-- 96_v2.6에서_v2.7로.sql · 이미 v2.6으로 테이블을 만든 계정(예: HEEMANG)에만 실행 · 새로 만드는 계정은 01_schema.sql만 실행하면 됨
-- 실행: 프로젝트 계정으로 접속 → 스크립트 실행(F5) · DDL이라 실행 즉시 반영(ROLLBACK 안 됨)

-- 0) 먼저 확인: 아래 결과가 전부 0이어야 NOT NULL·CHECK 추가가 성공함 (0이 아니면 해당 행을 먼저 고침)
SELECT 'INQUIRY.STATUS NULL' 항목, COUNT(*) 건수 FROM INQUIRY WHERE STATUS IS NULL
UNION ALL SELECT 'MEMBER 이메일 대문자', COUNT(*) FROM MEMBER WHERE EMAIL <> LOWER(EMAIL)
UNION ALL SELECT 'INCOME 음수', COUNT(*) FROM INCOME WHERE TOTAL_SALARY < 0 OR WITHHELD_TAX < 0 OR SOCIAL_INSURANCE < 0 OR DEPENDENTS < 0 OR MONTHLY_RENT < 0 OR HOUSING_SAVING < 0 OR PENSION_SAVING < 0;

-- 1) PREDICTION.WITHHELD_TAX 삭제 (PREDICTION_INPUT.WITHHELD_TAX와 같은 값)
ALTER TABLE PREDICTION DROP COLUMN WITHHELD_TAX;

-- 2) 기본값 있는 칸 NOT NULL (INSERT에 칸을 적고 NULL(파이썬 None)을 넣으면 DEFAULT가 적용되지 않음)
ALTER TABLE MEMBER MODIFY (MILITARY_MONTHS NOT NULL, HOMELESS_HEAD_YN NOT NULL, UPDATED_AT NOT NULL);
ALTER TABLE INCOME MODIFY (SOCIAL_INSURANCE NOT NULL, DEPENDENTS NOT NULL, MONTHLY_RENT NOT NULL, HOUSING_SAVING NOT NULL, PENSION_SAVING NOT NULL, SME_REDUCTION_YN NOT NULL, UPDATED_AT NOT NULL);
ALTER TABLE CARD_UPLOAD MODIFY (ROW_COUNT NOT NULL, UPLOADED_AT NOT NULL);
ALTER TABLE SPEND_CATEGORY MODIFY (USE_YN NOT NULL);
ALTER TABLE MERCHANT_LIST MODIFY (MATCH_TYPE NOT NULL, USE_YN NOT NULL);
ALTER TABLE EXPENSE MODIFY (USER_EDITED_YN NOT NULL);
ALTER TABLE TAX_BRACKET MODIFY (BASE_AMOUNT NOT NULL);
ALTER TABLE BENEFIT_CONDITION MODIFY (HOMELESS_HEAD_REQ_YN NOT NULL);
ALTER TABLE PREDICTION MODIFY (SCENARIO_NAME NOT NULL, PREDICTED_AT NOT NULL);
ALTER TABLE PREDICTION_INPUT MODIFY (SOCIAL_INSURANCE NOT NULL, DEPENDENTS NOT NULL, MONTHLY_RENT NOT NULL, HOUSING_SAVING NOT NULL, PENSION_SAVING NOT NULL, SME_REDUCTION_YN NOT NULL, HOMELESS_HEAD_YN NOT NULL);
ALTER TABLE PREDICTION_DETAIL MODIFY (BASE_AMOUNT NOT NULL, DEDUCTION_AMOUNT NOT NULL);
ALTER TABLE RECOMMENDATION MODIFY (CREATED_AT NOT NULL);
ALTER TABLE CHAT_SESSION MODIFY (STARTED_AT NOT NULL);
ALTER TABLE CHAT_MESSAGE MODIFY (CREATED_AT NOT NULL);
ALTER TABLE INQUIRY MODIFY (STATUS NOT NULL, CREATED_AT NOT NULL);
ALTER TABLE ACCESS_LOG MODIFY (ACCESSED_AT NOT NULL);
ALTER TABLE PASSWORD_RESET MODIFY (USED_YN NOT NULL, CREATED_AT NOT NULL);

-- 3) 값 제한 추가
ALTER TABLE MEMBER ADD CONSTRAINT CK_MEMBER_EMAIL_LOWER CHECK (EMAIL = LOWER(EMAIL));
ALTER TABLE MEMBER ADD CONSTRAINT CK_MEMBER_MILITARY CHECK (MILITARY_MONTHS >= 0);
ALTER TABLE INCOME ADD CONSTRAINT CK_INCOME_AMOUNT CHECK (TOTAL_SALARY >= 0 AND WITHHELD_TAX >= 0 AND SOCIAL_INSURANCE >= 0 AND DEPENDENTS >= 0
  AND MONTHLY_RENT >= 0 AND HOUSING_SAVING >= 0 AND PENSION_SAVING >= 0);
ALTER TABLE PREDICTION_INPUT ADD CONSTRAINT CK_PRED_INPUT_AMOUNT CHECK (TOTAL_SALARY >= 0 AND WITHHELD_TAX >= 0 AND SOCIAL_INSURANCE >= 0 AND DEPENDENTS >= 0
  AND MONTHLY_RENT >= 0 AND HOUSING_SAVING >= 0 AND PENSION_SAVING >= 0);

COMMENT ON COLUMN MEMBER.EMAIL IS '이메일(소문자로만 저장, 아이디 찾기·비밀번호 재설정 인증용, 화면 마스킹)';

-- 4) 확인: CHECK 29 · PREDICTION 칸 10개
SELECT (SELECT COUNT(*) FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME LIKE 'CK\_%' ESCAPE '\') CHECK수,
       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'PREDICTION') PREDICTION_칸수 FROM DUAL;
