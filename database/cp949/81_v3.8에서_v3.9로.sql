SELECT (SELECT COUNT(*) FROM USER_TABLES) AS 테이블_수,
       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE TABLE_NAME IN (SELECT TABLE_NAME FROM USER_TABLES)) AS 칸_수,
       (SELECT COUNT(*) FROM USER_CONSTRAINTS WHERE CONSTRAINT_TYPE = 'C' AND CONSTRAINT_NAME LIKE 'CK\_%' ESCAPE '\') AS CHECK_수,
       (SELECT COUNT(*) FROM USER_CONSTRAINTS WHERE CONSTRAINT_TYPE = 'U') AS UNIQUE_수,
       (SELECT COUNT(*) FROM USER_INDEXES WHERE INDEX_NAME LIKE 'IX\_%' ESCAPE '\') AS 인덱스_수,
       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE COLUMN_NAME = 'SOCIAL_INSURANCE') AS 옛_칸,      -- 0
       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE COLUMN_NAME IN ('NATIONAL_PENSION', 'HEALTH_INSURANCE')) AS 새_칸,  -- 4
       (SELECT COUNT(*) FROM DEDUCTION_TYPE) AS 기준값_행,   -- 46 (2026 25 + 2025 21)
       (SELECT COUNT(*) FROM TAX_BRACKET) AS 구간_행,        -- 30
       (SELECT COUNT(*) FROM BENEFIT_CONDITION) AS 혜택_행,  -- 6
       (SELECT COUNT(*) FROM INCOME WHERE DATA_ORIGIN = 'GENERATED' AND HEALTH_INSURANCE = 0) AS 건강보험료_빈_가상회원,  -- 0
       (SELECT COUNT(*) FROM INCOME) AS 소득_행,
       (SELECT COUNT(*) FROM PREDICTION_INPUT) AS 예측입력_행
  FROM DUAL;

