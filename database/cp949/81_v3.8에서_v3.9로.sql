-- 가상 회원 1,000명: 총급여 × 급여 구간별 비율 (국세통계 4-2-4 · 2024년 귀속 · 「연금보험료공제 국민연금보험료 금액」÷「총급여」, 「특별공제 보험료 금액」÷「총급여」 · 소수 7자리)
--   05_가상데이터_생성.py · 03_데이터적재.sql · 가상데이터/INCOME.csv 와 같은 값 (예: INCOME_ID 1 총급여 2,384만 → 국민연금 719,260 · 건강보험료 657,940)
MERGE INTO INCOME i
USING (SELECT i2.INCOME_ID, ROUND(i2.TOTAL_SALARY * b.RN, -1) AS NP, ROUND(i2.TOTAL_SALARY * b.RI, -1) AS HI_AMT
         FROM INCOME i2
         JOIN (
            SELECT          0 AS LO,   10000000 AS HI, 0.0121974 AS RN, 0.0047743 AS RI FROM DUAL  -- 1천만 이하
            UNION ALL
            SELECT   10000000 AS LO,   15000000 AS HI, 0.0244429 AS RN, 0.0094829 AS RI FROM DUAL  -- 1.5천만 이하
            UNION ALL
            SELECT   15000000 AS LO,   20000000 AS HI, 0.0265409 AS RN, 0.0165834 AS RI FROM DUAL  -- 2천만 이하
            UNION ALL
            SELECT   20000000 AS LO,   30000000 AS HI, 0.0301704 AS RN, 0.0275980 AS RI FROM DUAL  -- 3천만 이하
            UNION ALL
            SELECT   30000000 AS LO,   40000000 AS HI, 0.0320524 AS RN, 0.0421408 AS RI FROM DUAL  -- 4천만 이하
            UNION ALL
            SELECT   40000000 AS LO,   45000000 AS HI, 0.0319851 AS RN, 0.0453155 AS RI FROM DUAL  -- 4.5천만 이하
            UNION ALL
            SELECT   45000000 AS LO,   50000000 AS HI, 0.0318056 AS RN, 0.0458342 AS RI FROM DUAL  -- 5천만 이하
            UNION ALL
            SELECT   50000000 AS LO,   60000000 AS HI, 0.0312768 AS RN, 0.0459693 AS RI FROM DUAL  -- 6천만 이하
            UNION ALL
            SELECT   60000000 AS LO,   80000000 AS HI, 0.0286317 AS RN, 0.0456002 AS RI FROM DUAL  -- 8천만 이하
            UNION ALL
            SELECT   80000000 AS LO,  100000000 AS HI, 0.0240583 AS RN, 0.0452215 AS RI FROM DUAL  -- 1억 이하
            UNION ALL
            SELECT  100000000 AS LO,  200000000 AS HI, 0.0209572 AS RN, 0.0468365 AS RI FROM DUAL  -- 2억 이하
            UNION ALL
            SELECT  200000000 AS LO,  300000000 AS HI, 0.0107838 AS RN, 0.0455383 AS RI FROM DUAL  -- 3억 이하
            UNION ALL
            SELECT  300000000 AS LO,  500000000 AS HI, 0.0064071 AS RN, 0.0447743 AS RI FROM DUAL  -- 5억 이하
            UNION ALL
            SELECT  500000000 AS LO, 1000000000 AS HI, 0.0033472 AS RN, 0.0427600 AS RI FROM DUAL  -- 10억 이하
            UNION ALL
            SELECT 1000000000 AS LO,       NULL AS HI, 0.0009833 AS RN, 0.0303036 AS RI FROM DUAL  -- 10억 초과
              ) b ON (i2.TOTAL_SALARY > b.LO OR b.LO = 0) AND (b.HI IS NULL OR i2.TOTAL_SALARY <= b.HI)
        WHERE i2.DATA_ORIGIN = 'GENERATED') s
   ON (i.INCOME_ID = s.INCOME_ID)
 WHEN MATCHED THEN UPDATE SET i.NATIONAL_PENSION = s.NP, i.HEALTH_INSURANCE = s.HI_AMT;
COMMIT;

