-- ─────────────────────────────────────────────
-- 0) 실행 전 확인 - 테이블 20 · 칸 208 · CHECK 49 · UNIQUE 12 · 인덱스 25 · 옛 칸 2 · 새 칸 0 · 기준값 22 · 구간 15 · 혜택 3 · 성별 빈 일반회원 0 이어야 함 (다르면 멈추고 알려 주세요)
-- ─────────────────────────────────────────────
SELECT (SELECT COUNT(*) FROM USER_TABLES) AS 테이블_수,
       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE TABLE_NAME IN (SELECT TABLE_NAME FROM USER_TABLES)) AS 칸_수,
       (SELECT COUNT(*) FROM USER_CONSTRAINTS WHERE CONSTRAINT_TYPE = 'C' AND CONSTRAINT_NAME LIKE 'CK\_%' ESCAPE '\') AS CHECK_수,
       (SELECT COUNT(*) FROM USER_CONSTRAINTS WHERE CONSTRAINT_TYPE = 'U') AS UNIQUE_수,
       (SELECT COUNT(*) FROM USER_INDEXES WHERE INDEX_NAME LIKE 'IX\_%' ESCAPE '\') AS 인덱스_수,
       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE COLUMN_NAME = 'SOCIAL_INSURANCE') AS 옛_칸,      -- 2 (INCOME · PREDICTION_INPUT)
       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE COLUMN_NAME IN ('NATIONAL_PENSION', 'HEALTH_INSURANCE')) AS 새_칸,  -- 0
       (SELECT COUNT(*) FROM DEDUCTION_TYPE) AS 기준값_행,   -- 22
       (SELECT COUNT(*) FROM TAX_BRACKET) AS 구간_행,        -- 15
       (SELECT COUNT(*) FROM BENEFIT_CONDITION) AS 혜택_행,  -- 3
       (SELECT COUNT(*) FROM MEMBER WHERE GENDER IS NULL AND ROLE <> 'ADMIN' AND STATUS <> 'WITHDRAWN') AS 성별_빈_일반회원,  -- 0 (0이 아니면 1)의 CHECK 추가가 실패함)
       (SELECT COUNT(*) FROM INCOME) AS 소득_행,
       (SELECT COUNT(*) FROM INCOME WHERE DATA_ORIGIN <> 'GENERATED') AS 소득_직접입력_행,  -- 보통 0 (있으면 아래 2) 참고)
       (SELECT COUNT(*) FROM PREDICTION_INPUT) AS 예측입력_행
  FROM DUAL;

